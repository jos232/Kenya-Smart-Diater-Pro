"use strict";

/* ==========================================
   OPEN FINANCIAL SERVICES
========================================== */

function openFinancialServices() {

    const financial = document.getElementById("financialServices");

    if (financial) {

        financial.style.display = "block";

    }

}

/* ==========================================
   CLOSE FINANCIAL SERVICES
========================================== */

function closeFinancialServices() {

    const financial = document.getElementById("financialServices");

    if (financial) {

        financial.style.display = "none";

    }

}